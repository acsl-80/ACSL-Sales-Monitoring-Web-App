CREATE OR REPLACE FUNCTION public.calculate_sale_status()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
  -- Define variables for status calculation
  DECLARE
    required_fields_complete BOOLEAN;
    has_signature BOOLEAN;
    has_stove_image BOOLEAN;
    has_agreement_image BOOLEAN;
    calculated_status TEXT;
  BEGIN
    -- Check if all required fields are present and not empty
    required_fields_complete := (
      NEW.transaction_id IS NOT NULL AND trim(NEW.transaction_id) != '' AND
      NEW.stove_serial_no IS NOT NULL AND trim(NEW.stove_serial_no) != '' AND
      NEW.sales_date IS NOT NULL AND
      NEW.contact_person IS NOT NULL AND trim(NEW.contact_person) != '' AND
      NEW.contact_phone IS NOT NULL AND trim(NEW.contact_phone) != '' AND
      NEW.end_user_name IS NOT NULL AND trim(NEW.end_user_name) != '' AND
      NEW.phone IS NOT NULL AND trim(NEW.phone) != '' AND
      NEW.partner_name IS NOT NULL AND trim(NEW.partner_name) != '' AND
      NEW.amount IS NOT NULL AND NEW.amount > 0
    );
    
    -- Check for signature
    has_signature := (NEW.signature IS NOT NULL AND trim(NEW.signature) != '');
    
    -- Check for images
    has_stove_image := (NEW.stove_image_id IS NOT NULL);
    has_agreement_image := (NEW.agreement_image_id IS NOT NULL);
    
    -- Calculate status based on completeness (don't override 'assigned' status)
    IF NEW.status != 'assigned' THEN
      IF required_fields_complete AND has_signature AND has_stove_image AND has_agreement_image THEN
        calculated_status := 'completed';
      ELSIF required_fields_complete AND (has_signature OR has_stove_image OR has_agreement_image) THEN
        calculated_status := 'pending';
      ELSE
        calculated_status := 'incomplete';
      END IF;
      
      -- Set the calculated status
      NEW.status := calculated_status;
    END IF;
    
    RETURN NEW;
  END;
END;
$function$
;
CREATE OR REPLACE FUNCTION public.cancel_purchase(_transfer_id uuid, _reason text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  _is_admin boolean;
  _transfer public.stove_transfer_history%ROWTYPE;
  _stove_ids text[];
  _blocking_count integer;
  _new_id uuid;
BEGIN
  SELECT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'super_admin')
  INTO _is_admin;
  IF NOT _is_admin THEN
    RAISE EXCEPTION 'Only super admins can cancel purchases';
  END IF;

  IF _reason IS NULL OR length(btrim(_reason)) < 5 THEN
    RAISE EXCEPTION 'A cancellation reason of at least 5 characters is required';
  END IF;

  SELECT * INTO _transfer FROM public.stove_transfer_history WHERE id = _transfer_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Transfer % not found', _transfer_id;
  END IF;

  SELECT ARRAY(
    SELECT jsonb_array_elements(_transfer.stove_ids)->>'stove_id'
  ) INTO _stove_ids;

  IF _stove_ids IS NOT NULL AND array_length(_stove_ids, 1) IS NOT NULL THEN
    SELECT count(*) INTO _blocking_count
    FROM public.sales
    WHERE stove_serial_no = ANY(_stove_ids)
      AND COALESCE(is_archived, false) = false;

    IF _blocking_count > 0 THEN
      RAISE EXCEPTION 'Cannot cancel: % stove(s) are still tied to active sales', _blocking_count;
    END IF;
  END IF;

  INSERT INTO public.cancelled_purchases (
    original_transfer_id, transaction_id, organization_id, partner_id, partner_name,
    state, branch, sales_factory, sales_date, transfer_date,
    stove_count, stove_ids_snapshot, cancellation_reason, cancelled_by
  ) VALUES (
    _transfer.id, _transfer.transaction_id, _transfer.organization_id, _transfer.partner_id, _transfer.partner_name,
    _transfer.state, _transfer.branch, _transfer.sales_factory, _transfer.sales_date, _transfer.transfer_date,
    COALESCE(_transfer.stove_count, 0), COALESCE(_transfer.stove_ids, '[]'::jsonb), btrim(_reason), auth.uid()
  ) RETURNING id INTO _new_id;

  IF _stove_ids IS NOT NULL AND array_length(_stove_ids, 1) IS NOT NULL AND _transfer.organization_id IS NOT NULL THEN
    DELETE FROM public.stove_ids_base
    WHERE stove_id = ANY(_stove_ids)
      AND organization_id = _transfer.organization_id
      AND sale_id IS NULL;
  END IF;

  DELETE FROM public.stove_transfer_history WHERE id = _transfer_id;

  RETURN _new_id;
END;
$function$
;
