     AND sale_record.stove_serial_no IS NOT NULL 
     AND sale_record.end_user_name IS NOT NULL 
     AND sale_record.phone IS NOT NULL 
     AND sale_record.amount IS NOT NULL 
     AND sale_record.address_id IS NOT NULL 
