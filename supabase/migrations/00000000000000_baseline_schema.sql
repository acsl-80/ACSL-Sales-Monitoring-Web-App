-- Baseline: the schema this project was actually built with.
--
-- WHY THIS FILE EXISTS
--
-- This project was built through the Supabase dashboard, not the CLI. As a
-- result supabase_migrations.schema_migrations in production held ZERO rows,
-- and no migration in this repository ever created the core tables: sales,
-- organizations, profiles, stove_ids_base, addresses or uploads. Every later
-- migration alters tables that nothing creates.
--
-- The practical cost was that no environment could be stood up from this
-- repository at all. Supabase branching builds a preview database by running
-- these migrations against an empty Postgres, so branching could not work, and
-- the local stack was missing the auth triggers for the same reason.
--
-- This is the step Supabase documents as "Preparing your Git repository":
-- supabase db pull, then commit. It was never done. This file is that.
--
-- CONTENTS
--
-- 1. schema-baselines/sales_public_baseline.sql, an introspection of the live
--    public schema: extensions, tables, constraints, indexes, RLS policies,
--    functions and views.
-- 2. schema-baselines/sales_supplemental_baseline.sql: auth trigger functions,
--    the auth.users triggers, and storage buckets and policies.
--
-- Timestamped 00000000000000 so it runs before every existing migration. Those
-- migrations then re-apply on top harmlessly: they are guarded with IF EXISTS
-- or IF NOT EXISTS, and every destructive statement in the partner-purge pair
-- is commented out. Verified, not assumed.
--
-- DELIBERATELY EXCLUDED: public.backup_partpaid_outright_20260815, a dated
-- one-off backup table present in production. It is operational debris rather
-- than schema, so a rebuilt environment should not carry it.
--
-- PRODUCTION MUST HAVE THIS MARKED APPLIED, NEVER RUN:
--   supabase migration repair --status applied 00000000000000

