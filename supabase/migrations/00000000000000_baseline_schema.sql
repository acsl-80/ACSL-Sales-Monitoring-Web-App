CREATE OR REPLACE FUNCTION public.get_sales_history(p_organization_id uuid, p_user_id uuid DEFAULT NULL::uuid, p_limit integer DEFAULT 50, p_offset integer DEFAULT 0, p_action_type character varying DEFAULT NULL::character varying, p_start_date timestamp without time zone DEFAULT NULL::timestamp without time zone, p_end_date timestamp without time zone DEFAULT NULL::timestamp without time zone)
 RETURNS TABLE(id uuid, sale_id uuid, action_type character varying, action_description text, field_changes jsonb, performed_by uuid, performed_at timestamp with time zone, transaction_id character varying, sale_amount numeric, sale_status character varying, performer_name text, performer_email text)
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
    RETURN QUERY
    SELECT 
        sh.id,
        sh.sale_id,
        sh.action_type,
        sh.action_description,
        sh.field_changes,
        sh.performed_by,
        sh.performed_at,
        s.transaction_id,
        s.amount as sale_amount,
        s.status as sale_status,
        p.full_name as performer_name,
        p.email as performer_email
    FROM sales_history sh
    JOIN sales s ON s.id = sh.sale_id
    JOIN profiles p ON p.id = sh.performed_by
    WHERE s.organization_id = p_organization_id
        AND (p_user_id IS NULL OR sh.performed_by = p_user_id)
        AND (p_action_type IS NULL OR sh.action_type = p_action_type)
        AND (p_start_date IS NULL OR sh.performed_at >= p_start_date)
        AND (p_end_date IS NULL OR sh.performed_at <= p_end_date)
    ORDER BY sh.performed_at DESC
    LIMIT p_limit OFFSET p_offset;
END;
$function$
;
