CREATE OR REPLACE FUNCTION public.manual_create_sales_history(p_sale_id uuid, p_action_type character varying, p_action_description text, p_field_changes jsonb DEFAULT NULL::jsonb, p_performed_by uuid DEFAULT NULL::uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    history_id UUID;
    user_id UUID;
BEGIN
    -- Use provided user or current auth user
    user_id := COALESCE(p_performed_by, auth.uid());
    
    -- If still no user, try custom setting
    IF user_id IS NULL THEN
        user_id := current_setting('app.current_user_id', true)::UUID;
    END IF;
    
    IF user_id IS NULL THEN
        RAISE EXCEPTION 'No user context available for history creation';
    END IF;

    -- Insert history record
    INSERT INTO sales_history (
        sale_id,
        action_type,
        action_description,
        field_changes,
        performed_by,
        performed_at
    ) VALUES (
        p_sale_id,
        p_action_type,
        p_action_description,
        COALESCE(p_field_changes, '{}'::jsonb),
        user_id,
        NOW()
    ) RETURNING id INTO history_id;

    RETURN history_id;
END;
$function$
;
